async def question_analysis(query, token_tracker: Optional["TokenTracker"] = None):
        logging.info("开始调用question_analysis")
        # 第一步：意图识别
        intent_prompt = f"""
        【任务】我将向你提出一个【问题】{query}，请判断其是定性问题还是定量问题。若问题有缺失，请根据金融行业从业人员的角度补全后再判断。

        【要求】根据以下标准进行判断：
            **Y**：定性问题：
                **定义**：涉及非数值信息，关注对事物的性质、特征和本质的描述和理解。判断标准包括但不限于：
                **判断标准**：a.主要涉及非数值信息，关注性质、特征或本质的描述。例如：“影响E公司股价下跌的因素是什么？”、“金融软件的收费方式”。
                             b.询问概念、战略、市场、趋势分析等理解。例如：“供应链中断如何影响汽车行业？”、“2026年经济预测”。
                             c.讨论报告、分析或某篇文章的内容。例如：“资源优质管理出众，业绩稳健高股息”。
                             d.包含定性关键词（如“解释”、“描述”、“分析”、“观点”等）。
                             e.包含数字或量化词，但缺乏明确数据请求。例如：“马斯克100亿”，“基本面量化”。

            **N**：定量问题：
                **定义**：涉及数值数据和统计分析或有关所有可放在数据库中创建表格进行量化的内容，关注对事物量化特征的测量和比较。判断标准包括但不限于：
                **判断标准**：a.涉及具体数值、指标、公司财报、公司公告、公司数据或财务数据等。例如：“A公司2022年的净利润是多少？”、“华为机器人的供应商有哪些？”。
                             b.涉及计算、比较或模式识别。例如：“D公司市盈率与行业平均水平相比如何？”。
                             c.包含财务比率、经济指标或统计数据等（如“比例”、“数值”、“数据”、“增长率”等）。
                             d.需要数据查找、计算或比较来回答。例如：“电子行业2024年Q3哪些A股超预期”。
                             e.请求具体的公司业务、产品、生产能力、客户行业分布等信息。例如：“永创智能的客户行业分布”。 
                             f.涉及公司的股权关系、持股变动、股东结构查询等投资信息。例如：“蚂蚁金服参股的上市公司？”
                             g.涉及公司基本信息或金融信息（如：利润、营收、股东分红、持股、持仓、股权激励计划、市场渠道布局、业务结构等）。
                             h.问题涉及基金的持仓、净值、份额变动、基金经理及其相关信息。
                             i.问题涉及股市标签（如ETF、QDII基金等）。
                             j.问题与主板、港股、科创板的财务、股本、行情、基本信息等数据相关。

            当问题可能既是定性又是定量时，优先判断为定量问题（N）。

            请直接输出结果（Y或N），不要输出任何思考过程。  
                """
        intent_res = await call_llm(prompt=intent_prompt, model="gpt-4.1", token_tracker=token_tracker)
        if intent_res == "Y":
            intent_display = "定性分析"
        else:
            intent_display = "定量查数据"

        return intent_display


